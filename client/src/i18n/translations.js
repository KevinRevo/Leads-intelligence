export function t(key, lang = 'fr', params = {}) {
  const dict = translations[lang] || translations.fr;
  let text = dict[key] || translations.fr[key] || key;
  if (params && typeof params === 'object') {
    for (const [pKey, pVal] of Object.entries(params)) {
      text = text.replace(new RegExp(`\\{${pKey}\\}`, 'g'), pVal);
    }
  }
  return text;
}

export function translateSector(sectorName, lang = 'fr') {
  if (!sectorName) return lang === 'en' ? 'B2B Services' : 'Services B2B';
  const s = sectorName.toLowerCase();
  if (lang === 'en') {
    if (s.includes('import') || s.includes('export')) return 'Import / Export';
    if (s.includes('immobilier')) return 'Real Estate';
    if (s.includes('consulting') || s.includes('conseil')) return 'Consulting & Strategy';
    if (s.includes('tech') || s.includes('logiciel')) return 'Tech & Software';
    if (s.includes('holding') || s.includes('participations')) return 'Holdings & Participations';
    if (s.includes('industrie') || s.includes('ingénierie') || s.includes('ingenierie')) return 'Industry & Engineering';
    if (s.includes('transport') || s.includes('logistique')) return 'Transport & Logistics';
    if (s.includes('restauration') || s.includes('hôtellerie') || s.includes('hotellerie')) return 'Hospitality & Catering';
    if (s.includes('btp') || s.includes('construction') || s.includes('travaux')) return 'Construction & Civil Works';
    if (s.includes('santé') || s.includes('sante') || s.includes('médical') || s.includes('medical')) return 'Healthcare & Medical';
    if (s.includes('commerce') || s.includes('vente')) return 'Retail & E-Commerce';
    if (s.includes('marketing') || s.includes('com')) return 'Marketing & Com';
    if (s.includes('services')) return 'B2B Services';
    return sectorName;
  }
  return sectorName;
}

export function countryLabel(code, lang = 'fr') {
  const map = {
    fr: { FR: 'France', CH: 'Suisse', BE: 'Belgique', LU: 'Luxembourg', NL: 'Pays-Bas' },
    en: { FR: 'France', CH: 'Switzerland', BE: 'Belgium', LU: 'Luxembourg', NL: 'Netherlands' }
  };
  return (map[lang] || map.fr)[code] || 'France';
}
